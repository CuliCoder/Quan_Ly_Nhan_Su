        private void btnDuyetTangLuong_Click(object sender, EventArgs e)
        {
            try
            {
                DataGridViewRow row = null;
                if (dataTangLuong.SelectedRows != null && dataTangLuong.SelectedRows.Count > 0)
                    row = dataTangLuong.SelectedRows[0];
                else if (dataTangLuong.CurrentRow != null)
                    row = dataTangLuong.CurrentRow;

                if (row == null)
                {
                    MessageBox.Show("Vui lòng chọn một phiếu tăng lương để duyệt.", "Thông báo", MessageBoxButtons.OK, MessageBoxIcon.Information);
                    return;
                }

                int id;
                if (!int.TryParse(row.Cells["Id"]?.Value?.ToString(), out id))
                {
                    MessageBox.Show("Không xác định được Id phiếu tăng lương.", "Lỗi", MessageBoxButtons.OK, MessageBoxIcon.Error);
                    return;
                }

                if (listSalaryIncrease == null) listSalaryIncrease = salaryIncreaseBLL.GetAll() ?? new List<SalaryIncreaseDTO>();
                var increaseDto = listSalaryIncrease.FirstOrDefault(x => x.Id == id)
                                  ?? (salaryIncreaseBLL.GetAll() ?? new List<SalaryIncreaseDTO>()).FirstOrDefault(x => x.Id == id);

                if (increaseDto == null)
                {
                    MessageBox.Show("Phiếu tăng lương không tồn tại.", "Lỗi", MessageBoxButtons.OK, MessageBoxIcon.Error);
                    return;
                }

                string percentText = tbTangLuong?.Text?.Trim();
                if (string.IsNullOrWhiteSpace(percentText))
                {
                    MessageBox.Show("Vui lòng nhập phần trăm tăng lương.", "Thông báo", MessageBoxButtons.OK, MessageBoxIcon.Information);
                    return;
                }

                decimal parsed;
                if (!decimal.TryParse(percentText, out parsed))
                {
                    if (!decimal.TryParse(percentText, System.Globalization.NumberStyles.Any, System.Globalization.CultureInfo.InvariantCulture, out parsed))
                    {
                        MessageBox.Show("Phần trăm tăng không hợp lệ.", "Lỗi", MessageBoxButtons.OK, MessageBoxIcon.Error);
                        return;
                    }
                }

                if (parsed > 1m) parsed = parsed / 100m;

                increaseDto.PhanTramTang = parsed;
                increaseDto.NgayDuyet = DateTime.Now;
                increaseDto.TrangThai = "Đã duyệt";

                decimal luongHienTai = increaseDto.LuongHienTai;
                decimal luongMoi = Math.Round(luongHienTai + luongHienTai * parsed, 0);
                increaseDto.LuongMoi = luongMoi;

                bool okUpdateIncrease = salaryIncreaseBLL.Update(increaseDto);
                if (!okUpdateIncrease)
                {
                    MessageBox.Show("Cập nhật trạng thái phiếu tăng lương thất bại.", "Lỗi", MessageBoxButtons.OK, MessageBoxIcon.Error);
                    return;
                }

                if (listSalaryFull == null) listSalaryFull = salaryFullBLL.GetAllSalaryFull() ?? new List<SalaryFullDTO>();
                var salaryFull = listSalaryFull.FirstOrDefault(s =>
                {
                    try
                    {
                        var prop = s.GetType().GetProperty("MaNhanVien");
                        if (prop != null)
                        {
                            var val = prop.GetValue(s)?.ToString();
                            return string.Equals(val, increaseDto.MaNhanVien, StringComparison.OrdinalIgnoreCase);
                        }
                    }
                    catch { }
                    return false;
                });

                if (salaryFull != null)
                {
                    var salaryDto = new SalaryDTO
                    {
                        MaLuong = salaryFull.GetType().GetProperty("MaLuong")?.GetValue(salaryFull)?.ToString(),
                        MaNhanVien = increaseDto.MaNhanVien,
                        LuongCoBan = luongMoi,
                        LuongTheoGio = salaryFull.GetType().GetProperty("LuongTheoGio") != null
                            ? Convert.ToDecimal(salaryFull.GetType().GetProperty("LuongTheoGio").GetValue(salaryFull))
                            : 0m
                    };

                    var salaryBLL = new SalaryBLL();
                    bool okSalary = salaryBLL.UpdateSalary(salaryDto);
                    if (!okSalary)
                    {
                        MessageBox.Show("Phiếu tăng lương đã được cập nhật nhưng cập nhật lương cơ bản thất bại.", "Cảnh báo", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                    }
                }
                else
                {
                    MessageBox.Show("Đã duyệt phiếu tăng lương. Không tìm thấy bản ghi lương để cập nhật lương cơ bản (kiểm tra dữ liệu lương nhân viên).", "Thông báo", MessageBoxButtons.OK, MessageBoxIcon.Information);
                }

                listSalaryIncrease = salaryIncreaseBLL.GetAll();
                FillDataToSalaryIncreaseTable(listSalaryIncrease);

                listSalaryFull = salaryFullBLL.GetAllSalaryFull();
                FillDataToBangLuongTable(listSalaryFull);

                MessageBox.Show("Duyệt tăng lương thành công.", "Thành công", MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            catch (Exception ex)
            {
                MessageBox.Show("Lỗi khi duyệt tăng lương: " + ex.Message, "Lỗi", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }
    }
