        private async void AutoGenerateSalaryIncreaseOnStartup()
        {
            try
            {
                var result = await Task.Run(() =>
                {
                    int year = DateTime.Now.Year;
                    int created = 0;
                    int skipped = 0;

                    var existingIncreases = salaryIncreaseBLL.GetAll() ?? new List<SalaryIncreaseDTO>();

                    var allEvals = evaluationBLL.GetAll() ?? new List<EvaluationDTO>();
                    var evalsThisYear = allEvals.Where(ev => ev.NgayDanhGia.Year == year).ToList();

                    var employeeIds = evalsThisYear
                        .Select(ev => ev.MaNhanVien)
                        .Where(id => !string.IsNullOrWhiteSpace(id))
                        .Distinct()
                        .ToList();

                    foreach (var maNV in employeeIds)
                    {
                        bool already = existingIncreases.Any(s =>
                            s.MaNhanVien == maNV &&
                            (
                                !s.NgayDuyet.HasValue
                                || (s.NgayDuyet.HasValue && s.NgayDuyet.Value.Year == year)
                            ));

                        if (already)
                        {
                            skipped++;
                            continue;
                        }

                        double totalScore = 0;
                        try
                        {
                            totalScore = evaluationBLL.GetTotalEvaluationScore(maNV, year);
                        }
                        catch
                        {
                            skipped++;
                            continue;
                        }

                        if (totalScore < 0)
                        {
                            skipped++;
                            continue;
                        }

                        decimal percentIncrease = 0m;

                        if (totalScore >= 90)
                            percentIncrease = 0.20m;
                        else if (totalScore >= 80)
                            percentIncrease = 0.10m;
                        else if (totalScore >= 70)
                            percentIncrease = 0.07m;
                        else if (totalScore >= 50)
                            percentIncrease = 0.03m;

                        var dto = new SalaryIncreaseDTO
                        {
                            MaNhanVien = maNV,
                            DiemDanhGia = (float)totalScore,
                            PhanTramTang = percentIncrease,
                            LuongMoi = null,
                            NgayDuyet = null,
                            TrangThai = null
                        };

                        try
                        {
                            bool ok = salaryIncreaseBLL.Insert(dto);
                            if (ok)
                            {
                                created++;
                                existingIncreases.Add(dto);
                            }
                            else skipped++;
                        }
                        catch
                        {
                            skipped++;
                        }
                    }

                    return new { created, skipped, year };
                });

                try
                {
                    this.Invoke((Action)(() =>
                    {
                        listSalaryIncrease = salaryIncreaseBLL.GetAll();
                        FillDataToSalaryIncreaseTable(listSalaryIncrease);

                        if (result.created > 0)
                        {
                            MessageBox.Show($"Tự động tạo phiếu tăng lương cho năm {result.year}: {result.created} bản ghi đã tạo, {result.skipped} bị bỏ qua.", "Thông báo", MessageBoxButtons.OK, MessageBoxIcon.Information);
                        }
                    }));
                }
                catch { }
            }
            catch (Exception ex)
            {
                try { this.Invoke((Action)(() => MessageBox.Show("Lỗi khi tạo tự động phiếu tăng lương: " + ex.Message, "Lỗi", MessageBoxButtons.OK, MessageBoxIcon.Error))); } catch { }
            }
        }

        private void BtnTinhLuong_Click(object sender, EventArgs e)
        {
            try
            {
                DataGridViewRow row = null;
                if (dataBangLuong.SelectedRows != null && dataBangLuong.SelectedRows.Count > 0)
                {
                    row = dataBangLuong.SelectedRows[0];
                }
                else if (dataBangLuong.CurrentRow != null)
                {
                    row = dataBangLuong.CurrentRow;
                }

                if (row == null)
                {
                    MessageBox.Show("Vui lòng chọn một nhân viên để xuất phiếu lương.", "Thông báo", MessageBoxButtons.OK, MessageBoxIcon.Information);
                    return;
                }

                string maNhanVien = null;
                var colByName = dataBangLuong.Columns.Cast<DataGridViewColumn>()
                    .FirstOrDefault(c => string.Equals(c.Name, "MaNhanVien", StringComparison.OrdinalIgnoreCase) ||
                                         string.Equals(c.DataPropertyName, "MaNhanVien", StringComparison.OrdinalIgnoreCase) ||
                                         string.Equals(c.HeaderText, "Mã Nhân Viên", StringComparison.OrdinalIgnoreCase));

                if (colByName != null)
                {
                    maNhanVien = row.Cells[colByName.Index].Value?.ToString();
                }
                else if (row.Cells.Count > 1)
                {
                    maNhanVien = row.Cells[1]?.Value?.ToString();
                }

                if (string.IsNullOrWhiteSpace(maNhanVien))
                {
                    MessageBox.Show("Không lấy được mã nhân viên từ dòng đã chọn.", "Lỗi", MessageBoxButtons.OK, MessageBoxIcon.Error);
                    return;
                }

                using (var form = new BillFormGUI(maNhanVien))
                {
                    form.StartPosition = FormStartPosition.CenterParent;
                    form.ShowDialog(this);
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Lỗi khi xuất phiếu lương: {ex.Message}", "Lỗi", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

